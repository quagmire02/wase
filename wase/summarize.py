"""
One page with everything that has been run, for review without opening folders.

  python -m wase.summarize          # -> results/summary.md

Per run and seed: how far it got, what its labels looked like in each generation
(boxes, empty images, precision/recall against human labels, verify/oracle
counters). Then every evaluation set's mAP50 per condition. Reads only the small
JSON files that git tracks, so the page can be rebuilt from a fresh clone.
"""

import argparse
from pathlib import Path

from .common import default_results_dir, default_runs_dir, load_json, log


def f(v, nd=3):
    return "--" if v is None else f"{v:.{nd}f}"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", type=Path, default=default_runs_dir())
    ap.add_argument("--results", type=Path, default=default_results_dir())
    a = ap.parse_args()
    md = ["# Run summary (generated by `python -m wase.summarize`; do not edit)\n",
          "## Labels per generation\n",
          "| run | seed | gen | teacher conf | boxes | empty % | P vs human | R vs human | admitted | rejected | oracle matched / false / missed | trained |",
          "|---|:-:|:-:|:-:|:-:|:-:|:-:|:-:|:-:|:-:|:-:|:-:|"]
    for cfg in sorted(a.runs.resolve().glob("*/seed*/config.json")):
        run = cfg.parent
        gens = sorted(run.glob("gen*_labels.json"))
        if not gens:
            md.append(f"| {run.parent.name} | {run.name[4:]} | -- | | | | | | | | | "
                      f"{'yes' if (run / 'weights' / 'final.pt').exists() else 'no'} |")
        for g in gens:
            d = load_json(g)
            st, ag = d["label_stats"], d["agreement_with_human_labels"]
            orc = "/".join(str(st[k]) for k in ("oracle_matched", "oracle_false", "oracle_missed")) \
                if "oracle_matched" in st else ""
            done = (run / "weights" / f"gen{d['generation']}.pt").exists()
            md.append(f"| {run.parent.name} | {run.name[4:]} | {d['generation']} | {d['teacher_conf']} | "
                      f"{st['boxes']} | {100 * d['empty_fraction']:.1f} | {f(ag['precision'])} | {f(ag['recall'])} | "
                      f"{st.get('n_admitted', '')} | {st.get('n_rejected', '')} | {orc} | {'yes' if done else 'no'} |")
    for m in sorted(a.results.resolve().glob("*/metrics.json")):
        r = load_json(m)
        md += [f"\n## {r['set']} ({r['n_images']} images, {r['n_objects']} objects)\n",
               "| condition | seeds | mAP50 | sd | mAP50:95 | small | inst.-wt AP50 |", "|---|:-:|:-:|:-:|:-:|:-:|:-:|"]
        for lab, v in sorted(r["models"].items(), key=lambda kv: -(kv[1]["mAP50"]["mean"] or 0)):
            md.append(f"| {lab} | {v['mAP50']['n_seeds']} | {f(v['mAP50']['mean'])} | {f(v['mAP50']['std'])} | "
                      f"{f(v['mAP50_95']['mean'])} | {f(v['mAP_small']['mean'])} | {f(v['instance_weighted_AP50'])} |")
    out = a.results.resolve() / "summary.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    log(f"wrote {out}")


if __name__ == "__main__":
    main()
